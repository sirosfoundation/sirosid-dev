#!/usr/bin/env python3
"""Render wallet-backend and go-trust (PDP) config from the siros-id-stack chart.

sirosid-dev historically hand-maintained a parallel set of flat env vars
(docker-compose.test.yml's `wallet-backend` service, `--registry`/`--whitelist`
CLI flags for go-trust) that happen to drive the same underlying config schema
as the production Helm chart, but drift independently of it. Both
go-wallet-backend (pkg/config/config.go) and go-trust (pkg/config/config.go)
load one config struct via a YAML file (`--config`); Helm just renders that
YAML into a ConfigMap instead of a hand-written file.

This script renders the real chart with `helm template` (no cluster contact -
this only needs the chart on disk, see SIROS_ID_STACK_PATH) and extracts the
ConfigMap `data` blocks for wallet-backend and pdp verbatim, so any change to
the chart's templates/values flows into sirosid-dev automatically. The only
hand-written logic here is the small set of rewrites that are genuinely
environment-specific and have no values.yaml toggle to express them - see
patch_wallet_backend() per --target.

--target compose (default): sirosid-dev's local docker-compose stack.
  - wallet-backend's rp_origins/base_url/cors.allowed_origins/registry_url are
    built by helpers that hardcode an `https://` scheme (siros-id.origins.*,
    04-wallet-backend.yaml) - sirosid-dev serves everything over plain http.
  - wallet-backend's storage.mongodb is rendered for the MongoDB Community
    Operator (x509 mTLS SRV record) - sirosid-dev runs a single plain `mongo`
    container (docker-compose.vc-services.yml), so there's nothing to
    authenticate against and no cert volume to mount.
  PDP's whitelist is NOT patched here - see values-dev.yaml's `pdp:` block,
  which disables `default_whitelist` (hardcoded https placeholder hostnames)
  and supplies an equivalent whitelist of real compose-network URLs via
  `pdp.extraRegistries`, using the chart's own extension point instead of
  text surgery.

--target fly --env <name>: a named Fly.io environment (see scripts/fly-up.py).
  - Same https-scheme and mongodb-mTLS rewrites as compose, but pointed at
    Fly hostnames instead of localhost: `sirosid-<env>-<component>.fly.dev`
    (public, Fly automatic TLS) or `.internal` (Fly 6PN, private).
  - wallet-backend's public identity is `wallet-proxy`, not wallet-backend
    itself - wallet-backend has no Fly public service (see fly-up.py); a
    small nginx app (mirroring fixtures/wallet-proxy.conf) fronts it to also
    serve /.well-known/assetlinks.json for Android passkey verification,
    matching how local Android/tunnel testing already works (see
    docker-compose.test.yml's wallet-proxy service).
  - PDP's whitelist is likewise NOT patched here - the per-env values overlay
    generated by build_fly_values_overlay() supplies `pdp.extraRegistries`
    pointing at the env's own Fly-hosted vc-services, the same extension
    point values-dev.yaml uses for compose.

Output goes to fixtures/rendered/ (gitignored - regenerate with
`make render-helm-config` whenever siros-id-stack or values-dev.yaml change, or
via fly-up.py for a named environment). Secrets are generated once into
fixtures/rendered-secrets/ and reused on subsequent runs (idempotent, like
the chart's own `lookup`-based generator) - only used for --target compose;
--target fly's secrets live in Fly's own secret store (see fly_common.py).
"""
